async function getLiveUpdatesHandler (): Promise<LiveUpdate[]> {
  return getLiveUpdates(settings.databasePath);
}

async function importCardsHandler (): Promise<ImportCardResult> {

	try {
		const ptCardListModelReader = new ProjectJsonModelReader<OotpExportDataColumn>("ptCardListColumns.json")
		const ptCardListModel = await ptCardListModelReader.getJsonModels();

		const csvReader = new OotpCsvExportReader(ptCardListModel, [...settings.ootpRoot, ...settings.ptCardFile]);
		
		const db = getDatabase();
		const cardImporter = new PtCardImporter(db, csvReader);
		const importResult = await cardImporter.importPtCardsAsync();

		return importResult;

	}
	catch (err) {
		return ImportCardResult.FAIL;
	}

}

async function createLiveUpdate (e: IpcMainInvokeEvent, liveUpdateEffectiveDate: string): Promise<LiveUpdate | null> {

	try {

		const db = getDatabase();
		const liveUpdate = await createLiveUpdateHandlerAsync(db, liveUpdateEffectiveDate);
		return liveUpdate;

	}
	catch (err) {
		//TODO: log error
		return null;
	}

}

async function getExportedPtDataFiles () : Promise<PtDataExportFile[]> {

 	  const ptFolders = await PtFolderSearcher.getAllPtFolders(settings.ootpRoot);
 	  const htmlFiles = await PtFolderSearcher.locateHtmlFiles(ptFolders);

	  return htmlFiles.filter(f => f.exportState !== PtDataExportState.ERROR);

}

async function importTournamentFile (e: IpcMainInvokeEvent, request: ImportStatFileRequest): Promise<boolean> {

    const db = getDatabase();

    try {
      const stats = await TournamentStatsReader.getStats(request.statsFilePath);
      await TournamentStatsReader.writeStats(stats, db, {
          Description: request.description,
          TournamentTypeID: request.tournamentTypeID,
          TournamentStartDate: request.tournamentStartDate
      });
      await PtFolderOperations.deletePtDataFileAsync(request.statsFilePath);
    }
    catch (err) {
      //TODO: log
      return false;
    }

    return true;

}

